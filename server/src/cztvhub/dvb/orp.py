def nearest(lat: float, lon: float) -> tuple[str, str]:
    """(code, name) of the ORP whose definition point is nearest (equirectangular distance: fine at this scale)."""
    scale = math.cos(math.radians(lat))
    best = min(ORP, key=lambda o: (o[2] - lat) ** 2 + ((o[3] - lon) * scale) ** 2)
    return best[0], best[1]
